//! Signing narinfos with ed25519 keys in Nix's format.

use core::fmt;
use std::path::{Path, PathBuf};
use std::{fs, io};

use aws_lc_rs::signature::{self, Ed25519KeyPair};
use base64::Engine as _;
use base64::display::Base64Display;
use base64::engine::general_purpose::STANDARD;

/// The length of a secret key: the seed followed by the public key.
const SECRET_KEY_LEN: usize = 64;

/// The length of the seed part of a secret key.
const SEED_LEN: usize = 32;

/// A secret key as written by `nix key generate-secret`.
pub(crate) struct SigningKey {
    /// The key name, such as `cache.example.org-1`.
    name: String,
    /// The key pair.
    pair: Ed25519KeyPair,
    /// The public key as `<name>:<base64>`.
    public_key: String,
}

impl SigningKey {
    /// Reads a key file containing `<name>:<base64 secret key>`.
    pub(crate) fn load(path: &Path) -> Result<Self, SigningKeyError> {
        let text = fs::read_to_string(path).map_err(|source| SigningKeyError::Read {
            path: path.to_owned(),
            source,
        })?;
        Self::load_text(text.trim()).ok_or_else(|| SigningKeyError::Invalid {
            path: path.to_owned(),
        })
    }

    /// Parses `<name>:<base64 secret key>`.
    pub(crate) fn load_text(text: &str) -> Option<Self> {
        let (name, key) = text.split_once(':')?;
        let key = STANDARD.decode(key).ok()?;
        if name.is_empty() || key.len() != SECRET_KEY_LEN {
            return None;
        }
        let (seed, public) = key.split_at(SEED_LEN);
        let pair = Ed25519KeyPair::from_seed_and_public_key(seed, public).ok()?;
        Some(Self {
            name: name.to_owned(),
            public_key: format!("{name}:{}", STANDARD.encode(public)),
            pair,
        })
    }

    /// The public key as `<name>:<base64>`, for `trusted-public-keys`.
    pub(crate) fn public_key(&self) -> &str {
        &self.public_key
    }

    /// Signs a fingerprint.
    pub(crate) fn sign(&self, fingerprint: &[u8]) -> Signature<'_> {
        Signature {
            name: &self.name,
            signature: self.pair.sign(fingerprint),
        }
    }
}

/// A signature that displays as `<name>:<base64 signature>`.
pub(crate) struct Signature<'a> {
    /// The name of the key.
    name: &'a str,
    /// The signature.
    signature: signature::Signature,
}

impl fmt::Debug for Signature<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Signature")
            .field("name", &self.name)
            .finish_non_exhaustive()
    }
}

impl fmt::Display for Signature<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "{}:{}",
            self.name,
            Base64Display::new(self.signature.as_ref(), &STANDARD)
        )
    }
}

impl fmt::Debug for SigningKey {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("SigningKey")
            .field("name", &self.name)
            .finish_non_exhaustive()
    }
}

/// Errors from loading a signing key.
#[derive(Debug, thiserror::Error)]
pub(crate) enum SigningKeyError {
    /// The file isn't a Nix secret key.
    #[error("{} isn't a Nix secret key", path.display())]
    Invalid {
        /// The key file.
        path: PathBuf,
    },
    /// The file can't be read.
    #[error("failed to read {}", path.display())]
    Read {
        /// The key file.
        path: PathBuf,
        /// The error from the operating system.
        #[source]
        source: io::Error,
    },
}

#[cfg(test)]
pub(crate) mod tests {
    use aws_lc_rs::signature::{ED25519, UnparsedPublicKey};

    use super::*;

    /// A key for tests only, generated by `nix key generate-secret`.
    pub(crate) const TEST_KEY: &str = "test-1:gDQElRwG6hWQbzvWiPbOwXBTfsbJksJCSpVX/RYucmv/Qjzzg/\
                                       1fQ4UimSnxIDFlz+sk9nb4Z1Ws41Rc6LhzIg==";

    #[test]
    fn signs_fingerprints() {
        let key = SigningKey::load_text(TEST_KEY).unwrap();
        let signature = key.sign(b"fingerprint").to_string();
        let (name, signature) = signature.split_once(':').unwrap();
        assert_eq!(name, "test-1", "the key name prefixes the signature");
        let public = key.public_key();
        let (_, public) = public.split_once(':').unwrap();
        UnparsedPublicKey::new(&ED25519, STANDARD.decode(public).unwrap())
            .verify(b"fingerprint", &STANDARD.decode(signature).unwrap())
            .unwrap();
    }

    #[test]
    fn rejects_invalid_keys() {
        for text in ["", "test-1", ":AAAA", "test-1:AAAA", "test-1:not base64"] {
            assert!(SigningKey::load_text(text).is_none(), "{text:?} is invalid");
        }
    }
}
